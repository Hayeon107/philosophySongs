const homeView = document.querySelector("#homeView");
const detailView = document.querySelector("#detailView");
const songGrid = document.querySelector("#songGrid");
const detailContent = document.querySelector("#detailContent");
const pageTitle = document.querySelector("#pageTitle");
const backButton = document.querySelector("#backButton");

function renderHome() {
  pageTitle.textContent = "철학맨 김선중의 철학 노래방";
  backButton.classList.remove("visible");
  detailView.hidden = true;
  homeView.hidden = false;

  songGrid.innerHTML = songs.map(song => `
    <button class="song-card" type="button" data-id="${song.id}" aria-label="${escapeHtml(song.title)}">
      <div class="song-thumb">
        <img src="${song.thumbnail}" alt="${escapeHtml(song.title)}">
      </div>
      <div class="song-meta">
        <p class="song-title">${escapeHtml(song.title)}</p>
        <p class="song-artist">${escapeHtml(song.artist)}</p>
        <p class="song-original">${escapeHtml(song.original)}</p>
      </div>
    </button>
  `).join("");

  songGrid.querySelectorAll(".song-card").forEach(card => {
    card.addEventListener("click", () => openDetail(card.dataset.id));
  });
}

function openDetail(id) {
  const song = songs.find(item => item.id === id);
  if (!song) return;

  pageTitle.textContent = "철학 노래";
  backButton.classList.add("visible");
  homeView.hidden = true;
  detailView.hidden = false;

  detailContent.innerHTML = `
  <div class="detail">

    <!-- 상단 고정 영역 -->
    <div class="detail-hero">
      <a
        class="reel-link"
        href="${escapeAttribute(song.instagramUrl)}"
        target="_blank"
        rel="noopener noreferrer"
        aria-label="인스타그램 릴스 열기"
      >
        <div class="detail-thumb">
          <img
            src="${escapeAttribute(song.thumbnail)}"
            alt="${escapeHtml(song.title)}"
          >
        </div>
      </a>
      <p class="detail-title">
        ${escapeHtml(song.title)}
      </p>
    </div>
    <!-- 가사만 스크롤 -->
    <div class="lyrics-panel">
      <div class="lyrics">
        <p class="lyrics-heading">LYRICS</p>
        <p>${escapeHtml(song.lyrics)}</p>
        <p class="source-note">
          썸네일을 누르면 원본 인스타그램 릴스로 이동합니다.
        </p>
      </div>
    </div>
  </div>
`;

  history.pushState({ id }, "", `#${id}`);
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function goHome() {
  history.pushState({}, "", location.pathname);
  renderHome();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function escapeAttribute(value) {
  return escapeHtml(value);
}

backButton.addEventListener("click", goHome);

window.addEventListener("popstate", () => {
  const id = location.hash.slice(1);
  if (id) openDetailWithoutHistory(id);
  else renderHome();
});


renderHome();

if (location.hash) {
  openDetailWithoutHistory(location.hash.slice(1));
}
